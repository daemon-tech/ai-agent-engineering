#!/usr/bin/env python3
"""Rebuild graph/*.csv and graph/coverage.md from manuscript/, references.bib, references-verification.md.
Run from the repo root: python3 graph/build.py"""
import re, csv, glob, collections
TAGS = 'PR|PUB|PP|VC|EE'
# [OP] items linked to issues (matched by text in the [OP] line; issue titles checked by hand)
ISSUES = {r'Proposed taxonomy': 3, r'done predicate': 2}
# heuristic tag flags checked by hand and found to be false alarms (tag belongs to adjacent citation)
FALSE_ALARMS = {('packer2023memgpt', 'manuscript/00-introduction.md:108'),
                ('aleithan2024swebenchplus', 'manuscript/02-agentic-software-engineering.md:24'),
                ('anthropic2024effective', 'manuscript/03-agent-architectures.md:107')}
SKIP_OP = re.compile(r'Evidence classes|it is tagged \*\*\[OP\]\*\*')  # meta lines describing the tag

def slug(s): return re.sub(r'\W+', '-', s.lower()).strip('-')

ver = {}
for l in open('references-verification.md'):
    m = re.match(r'\| \d+ \| `([^`]+)` \| (\w+) \| (\S+)', l)
    if m: ver[m[1]] = (m[2], m[3])
bib = dict(re.findall(r'@\w+\{([^,]+),[\s\S]*?title\s*=\s*\{+([^}]+)', open('references.bib').read()))
nodes, edges, flags = [], [], []
cites, strong = collections.Counter(), collections.Counter()
for k in sorted(ver): nodes.append(('paper:' + k, 'paper', bib.get(k, '').strip(), ver[k][0], ver[k][1]))
for f in sorted(glob.glob('manuscript/*.md')):
    cid = f.split('/')[-1][:-3]; ch = 'chapter:' + cid; L = open(f).read().split('\n')
    nodes.append((ch, 'chapter', L[0].lstrip('# '), '', f)); sec = None
    for i, l in enumerate(L, 1):
        loc = f'{f}:{i}'
        if l.startswith('## '):
            sec = f'concept:{cid}/{slug(l[3:])}'
            nodes.append((sec, 'concept', l[3:].strip(), '', loc)); edges.append((ch, 'contains', sec, loc))
        if '[OP]' in l and not SKIP_OP.search(l):
            oq = f'open_question:{cid}/L{i}'
            label = re.sub(r'[*#>]|\[OP\]', '', l).strip()[:120]
            issue = next((n for p, n in ISSUES.items() if re.search(p, l)), None)
            nodes.append((oq, 'open_question', label, 'OP',
                          f'https://github.com/daemon-tech/ai-agent-engineering/issues/{issue}' if issue else loc))
            edges.append((sec or ch, 'raises', oq, loc))
        for k in dict.fromkeys(re.findall(r'@(\w+)', l)):
            if k not in ver: continue
            edges.append((sec or ch, 'cites', 'paper:' + k, loc)); cites[ch] += 1
            if ver[k][0] in ('PR', 'PUB'): strong[ch] += 1
            m = re.search(rf'\[({TAGS})\][^@]{{0,40}}\[@{k}\b|\[@{k}[^\]]*\]\s*\[({TAGS})\]', l)
            if m and (m[1] or m[2]) != ver[k][0]:
                fa = (k, loc) in FALSE_ALARMS
                flags.append((k, m[1] or m[2], ver[k][0], loc, 'false_alarm' if fa else 'unchecked'))
nodes = list(dict.fromkeys(nodes)); edges = list(dict.fromkeys(edges))
assert len({n[0] for n in nodes}) == len(nodes), 'duplicate node ids'
w = lambda p, h, rows: csv.writer(open(p, 'w', newline=''), lineterminator='\n').writerows([h] + rows)
w('graph/nodes.csv', ('id', 'type', 'label', 'evidence_class', 'source'), nodes)
w('graph/edges.csv', ('source', 'relation', 'target', 'citation'), edges)
w('graph/tag-flags.csv', ('key', 'nearby_tag', 'verified_class', 'location', 'hand_check'), flags)
with open('graph/coverage.md', 'w') as o:
    o.write('# Coverage per chapter\n\nCitation links per chapter and the share pointing to [PR] or [PUB] papers. Generated by build.py.\n\n'
            '| Chapter | Cites | PR/PUB | Share |\n|---|---|---|---|\n')
    for c in sorted(cites): o.write(f'| {c[8:]} | {cites[c]} | {strong[c]} | {strong[c]/cites[c]:.0%} |\n')
print(len(nodes), 'nodes', dict(collections.Counter(n[1] for n in nodes)), len(edges), 'edges', len(flags), 'flags')
